const slug = (s: string) => s.toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** True when this Ideas build type is a held recipe. */
export const isHeldType = (type: string | null | undefined) => !!type && HELD_TYPES.has(slug(type));
